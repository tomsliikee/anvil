//! Generates the stylesheet from the design tokens and bundles it, with the
//! rest of `data/`, into one GResource. Nothing in the CSS is typed by hand
//! except the rules in `data/style.template.css`, which only use
//! `var(--im-…)`.

use std::path::PathBuf;
use std::{env, fs};

use anvil_core::tokens::{Theme, Tokens, css_variables};

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    for input in ["../insights-mono/tokens.json", "../data/style.template.css", "../data"] {
        println!("cargo:rerun-if-changed={input}");
    }
    let json = fs::read_to_string("../insights-mono/tokens.json").expect("insights-mono/tokens.json");
    let tokens = Tokens::parse(&json).unwrap_or_else(|e| panic!("{e}"));
    let template = fs::read_to_string("../data/style.template.css").expect("data/style.template.css");
    let light = css_variables(&tokens, Theme::Light).unwrap_or_else(|e| panic!("{e}"));
    let dark = css_variables(&tokens, Theme::Dark).unwrap_or_else(|e| panic!("{e}"));
    // libadwaita answers the media query from its own colour scheme, so
    // Anvil's light/dark override counts, not only the system's.
    let header = "/* Generated by anvil/build.rs from insights-mono/tokens.json. Do not edit. */\n";
    fs::write(out.join("style.css"), format!("{header}{light}\n@media (prefers-color-scheme: dark) {{\n{dark}}}\n\n{template}")).unwrap();
    glib_build_tools::compile_resources(&[out.to_str().unwrap(), "../data"], "../data/anvil.gresource.xml", "anvil.gresource");
}
